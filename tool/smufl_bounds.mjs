// Writes lib/features/editor/smufl_bounds.dart: the ink box of each Bravura
// glyph named in lib/features/editor/smufl.dart, from alphaTab's Bravura.svg.
// Run with `node tool/smufl_bounds.mjs` after changing smufl.dart.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const svg = readFileSync(join(root, 'engine/node_modules/@coderline/alphatab/dist/font/Bravura.svg'), 'utf8');
const dart = readFileSync(join(root, 'lib/features/editor/smufl.dart'), 'utf8');

const codePoints = new Set();
for (const ch of dart) {
  const cp = ch.codePointAt(0);
  if (cp >= 0xe000 && cp <= 0xf8ff) codePoints.add(cp);
}
for (const [, hex] of dart.matchAll(/\\u\{([0-9a-fA-F]+)\}/g)) codePoints.add(parseInt(hex, 16));

// A Bézier curve stays inside its control points, so their box holds the ink; it can only be a little larger.
function bounds(d) {
  const tokens = d.match(/[a-zA-Z]|-?(?:\d+\.?\d*|\.\d+)(?:e-?\d+)?/g);
  let i = 0;
  let x = 0, y = 0, startX = 0, startY = 0, command = '';
  let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
  const take = () => Number(tokens[i++]);
  const see = (px, py) => {
    minX = Math.min(minX, px); maxX = Math.max(maxX, px);
    minY = Math.min(minY, py); maxY = Math.max(maxY, py);
  };
  const arity = { m: 2, l: 2, h: 1, v: 1, c: 6, s: 4, q: 4, t: 2, z: 0 };
  while (i < tokens.length) {
    if (/[a-zA-Z]/.test(tokens[i])) command = tokens[i++];
    const lower = command.toLowerCase();
    const relative = command === lower;
    if (lower === 'z') { x = startX; y = startY; continue; }
    const n = arity[lower];
    if (n === undefined) throw new Error(`path command ${command}`);
    const values = Array.from({ length: n }, take);
    const points = [];
    if (lower === 'h') points.push([relative ? x + values[0] : values[0], y]);
    else if (lower === 'v') points.push([x, relative ? y + values[0] : values[0]]);
    else for (let k = 0; k < n; k += 2) points.push(relative ? [x + values[k], y + values[k + 1]] : [values[k], values[k + 1]]);
    for (const [px, py] of points) see(px, py);
    [x, y] = points[points.length - 1];
    if (lower === 'm') { startX = x; startY = y; command = relative ? 'l' : 'L'; }
  }
  return [minX, minY, maxX, maxY].map(Math.round);
}

const entries = [];
for (const cp of [...codePoints].sort((a, b) => a - b)) {
  const hex = cp.toString(16);
  const glyph = new RegExp(`<glyph[^>]*unicode="&#x${hex};"[^>]*>`, 'i').exec(svg)?.[0];
  const d = glyph && /\sd="([^"]*)"/.exec(glyph)?.[1];
  if (!d) { console.warn(`no outline for U+${hex.toUpperCase()}`); continue; }
  const [left, bottom, right, top] = bounds(d);
  entries.push(`  0x${hex.toUpperCase()}: (left: ${left}, bottom: ${bottom}, right: ${right}, top: ${top}),`);
}

writeFileSync(
  join(root, 'lib/features/editor/smufl_bounds.dart'),
  `// Generated by tool/smufl_bounds.mjs from Bravura.svg; don't edit by hand.

/// Each glyph's ink box in font units, 1000 to the em, y up from the baseline.
const smuflBounds = <int, ({int left, int bottom, int right, int top})>{
${entries.join('\n')}
};
`,
);
console.log(`${entries.length} glyphs`);
